"""Convert the Leica watermark packs of 徕卡一瞬 into the data the Watermark tab renders.

Input : <pack>/assets/templates/<group>/<id>/{config.json,i18n.json,*.webp,*.png}
Output: js/wm-templates-data.js (layout trees, fonts, backgrounds, strings) and img/wm/<sha1>.png (every picture, deduplicated).

Usage : python scripts/build-watermark-templates.py "<path to leica-yishun>"
"""
import hashlib
import json
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT_JS = ROOT / "js" / "wm-templates-data.js"
OUT_IMG = ROOT / "img" / "wm"
GROUP_NAMES = {"leica": "Leica", "leica_17u": "Xiaomi 17 Ultra by Leica", "leica_18pm": "Xiaomi 18 Pro Max"}
# not drawn by the renderer: settings pictures, pickers, icons of the in-app menu
SKIP_FILE = re.compile(r"^(icon_|img_setting_base|leica_looks_|leica_lens_|cv_lens_|custom_icon_|icon_signature_)")
KEEP_NODE = ("type", "id", "orientation", "layout_width", "layout_height", "gravity", "layout_gravity", "margin_left", "margin_top",
             "background", "setting_optional_type", "text", "text_upper", "font_ref", "rect_params", "display_width", "display_height",
             "path", "degree", "enable", "childViews")


def slim(node: dict) -> dict:
    out = {k: node[k] for k in KEEP_NODE if k in node}
    if "childViews" in out:
        out["childViews"] = [slim(c) for c in out["childViews"]]
    return out


def store_image(path: Path, cache: dict[Path, list]) -> list:
    """[file in img/wm, width, height]"""
    if path not in cache:
        image = Image.open(path).convert("RGBA")
        name = hashlib.sha1(path.read_bytes()).hexdigest()[:12] + ".png"
        if not (OUT_IMG / name).exists():
            image.save(OUT_IMG / name)
        cache[path] = [name, image.width, image.height]
    return cache[path]


def read_strings(tpl: Path) -> dict[str, str]:
    path = tpl / "i18n.json"
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return {k: v.get("default") or v.get("en") or "" for k, v in data.items()}


def convert_template(tpl: Path, cache: dict[Path, list]) -> dict:
    cfg = json.loads((tpl / "config.json").read_text(encoding="utf-8"))
    strings = read_strings(tpl)
    files = {p.name: store_image(p, cache) for p in sorted(tpl.iterdir()) if p.suffix in (".webp", ".png") and not SKIP_FILE.match(p.name)}
    meta = cfg["metadata"]
    name_key = meta["name"].lstrip("@")
    layouts = {}
    for group in cfg["layout_group"]:
        for key, roots in group.items():
            layouts[key] = [slim(r) for r in roots]
    res = cfg["wmRes"]
    return {
        "id": meta["id"],
        "name": strings.get(name_key, meta["id"]),
        "layouts": layouts,
        "fonts": {k: {f: v[f] for f in ("size", "color", "typeface", "variation", "letterSpacing", "shadow") if f in v} for k, v in res["fonts"].items()},
        "backgrounds": [{k: b[k] for k in ("name", "value", "foreground") if k in b} for b in res.get("background", [])],
        "strings": {k: v for k, v in strings.items() if not k.endswith("_name")},
        "files": files,
    }


def main() -> int:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    pack = Path(sys.argv[1]) / "assets" / "templates"
    OUT_IMG.mkdir(parents=True, exist_ok=True)
    cache: dict[Path, list] = {}
    groups = []
    for gdir in sorted(p for p in pack.iterdir() if p.is_dir()):
        templates = [convert_template(t.parent, cache) for t in sorted(gdir.glob("*/config.json"), key=lambda p: int(p.parent.name))]
        groups.append({"id": gdir.name, "name": GROUP_NAMES.get(gdir.name, gdir.name), "templates": templates})
    body = json.dumps({"groups": groups}, ensure_ascii=False, separators=(",", ":"))
    OUT_JS.write_text("// Generated by scripts/build-watermark-templates.py from the 徕卡一瞬 pack; do not edit by hand.\nwindow.dr7WmData = " + body + ";\n", encoding="utf-8", newline="\n")
    print(f"{sum(len(g['templates']) for g in groups)} templates, {len({v[0] for v in cache.values()})} pictures, {OUT_JS.stat().st_size // 1024} KB data")
    return 0


if __name__ == "__main__":
    sys.exit(main())
